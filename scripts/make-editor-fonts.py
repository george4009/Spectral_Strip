# Regenerates Source/UI/EditorFonts.h: Latin subsets of Lato (SIL OFL 1.1), renamed because
# "Lato" is a Reserved Font Name and a subset is a modified version.
# Usage: python3 make_fonts.py /path/to/lato/ttf/dir output.h   (requires fonttools)
import sys, os, subprocess
from fontTools.ttLib import TTFont
src, out = sys.argv[1], sys.argv[2]
styles = [('Regular', 'Regular'), ('Bold', 'Bold'), ('Light', 'Light'), ('LightItalic', 'Light Italic')]
family = 'Strip Sans'
parts = ['// Generated by scripts/make-editor-fonts.py - do not edit.',
         '// "Strip Sans": Latin subsets of the Lato typeface by Lukasz Dziedzic, renamed as required',
         '// for modified versions. SIL Open Font License 1.1, see licenses/Lato-OFL.txt.',
         '#pragma once', '#include <cstddef>', '', 'namespace EditorFonts', '{']
for file, style in styles:
    tmp = f'subset-{file}.ttf'
    subprocess.run(['pyftsubset', os.path.join(src, f'Lato-{file}.ttf'),
                    '--unicodes=U+0020-007E,U+00A0-00FF,U+00B7,U+00D7,U+2013,U+2014,U+2026,U+2212,U+2022',
                    '--layout-features=kern', '--no-hinting', '--desubroutinize', f'--output-file={tmp}'], check=True)
    font = TTFont(tmp)
    for record in font['name'].names:
        if record.nameID in (1, 16): record.string = family
        elif record.nameID in (2, 17): record.string = style
        elif record.nameID == 4: record.string = f'{family} {style}'
        elif record.nameID == 6: record.string = f'StripSans-{file}'
        elif record.nameID == 3: record.string = f'{family} {style}; subset of Lato 2.015'
    font.save(tmp)
    data = open(tmp, 'rb').read()
    name = file[0].lower() + file[1:]
    rows = [','.join(str(b) for b in data[i:i + 24]) for i in range(0, len(data), 24)]
    parts.append(f'    inline const unsigned char {name}[] = {{\n' + ',\n'.join(rows) + '\n    };')
    parts.append(f'    inline constexpr std::size_t {name}Size = sizeof({name});')
parts.append('}')
open(out, 'w').write('\n'.join(parts) + '\n')
